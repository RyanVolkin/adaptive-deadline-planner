BEGIN;

CREATE TABLE public.tasks (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    name text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 100 AND name = btrim(name)),
    type text NOT NULL CHECK (type IN ('homework', 'project', 'reading', 'studying', 'other')),
    priority text NOT NULL CHECK (priority IN ('low', 'medium', 'high')),
    deadline date NOT NULL,
    original_estimate integer NOT NULL CHECK (original_estimate > 0),
    starting_estimate integer NOT NULL CHECK (starting_estimate > 0),
    adjusted_estimate integer NOT NULL CHECK (adjusted_estimate > 0),
    remaining_work integer NOT NULL CHECK (remaining_work >= 0),
    completion_pct integer NOT NULL DEFAULT 0 CHECK (completion_pct BETWEEN 0 AND 100),
    estimate_ratio double precision CHECK (estimate_ratio > 0),
    completed_at timestamptz,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    UNIQUE (id, user_id)
);

CREATE TABLE public.work_records (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id bigint NOT NULL REFERENCES public.tasks(id) ON DELETE CASCADE,
    minutes integer NOT NULL CHECK (minutes >= 0),
    completion_pct integer NOT NULL CHECK (completion_pct BETWEEN 0 AND 100),
    created_at timestamptz NOT NULL
);

CREATE TABLE public.schedule_entries (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id bigint NOT NULL,
    user_id uuid NOT NULL,
    date date NOT NULL,
    minutes integer NOT NULL CHECK (minutes > 0),
    FOREIGN KEY (task_id, user_id) REFERENCES public.tasks(id, user_id) ON DELETE CASCADE,
    UNIQUE (task_id, date)
);

CREATE INDEX tasks_history ON public.tasks (user_id, type, completed_at DESC, id DESC);
CREATE INDEX work_records_task ON public.work_records (task_id);
CREATE INDEX schedule_entries_user_date ON public.schedule_entries (user_id, date);

-- Planner data is accessed through Flask, not the public Supabase API.
ALTER TABLE public.tasks ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.work_records ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.schedule_entries ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.tasks, public.work_records, public.schedule_entries
    FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.tasks_id_seq, public.work_records_id_seq, public.schedule_entries_id_seq
    FROM PUBLIC, anon, authenticated;

-- The backend database role can bypass RLS, so repository queries must filter by user_id.
COMMIT;
